#!/usr/bin/env python3
"""
Convert a pickle file from evaluation to Inspect AI .eval format.

This script handles the conversion of pkl files generated by the evaluate.py script
into the Inspect AI .eval format, which can be viewed with Inspect AI tools.
"""
import pickle
import sys
import json
from pathlib import Path

# Add src to path for imports
sys.path.insert(0, str(Path(__file__).parent.parent.parent))

from exploration_hacking.util import InspectEvalAdapter

# Monkey patch the conversion function to handle JSON errors more gracefully
original_convert = InspectEvalAdapter._convert_chat_message_to_inspect

@staticmethod
def patched_convert(message):
    """Wrapper that handles JSON parsing errors in tool calls."""
    role = message.get("role", "user")

    if role == "assistant":
        # Handle tool calls with better error handling
        tool_calls_openai = message.get("tool_calls")
        if tool_calls_openai:
            from inspect_ai.model import ChatMessageAssistant
            from inspect_ai.tool import ToolCall

            content = message.get("content", "")
            tool_calls_inspect = []

            for tc in tool_calls_openai:
                try:
                    # Handle both ChatCompletionMessageToolCall objects and dicts
                    if hasattr(tc, 'id'):
                        tc_id = tc.id
                        tc_function = tc.function.name
                        # Safe JSON parsing with error handling
                        try:
                            tc_arguments = json.loads(tc.function.arguments) if isinstance(tc.function.arguments, str) else tc.function.arguments
                        except (json.JSONDecodeError, TypeError) as e:
                            # If JSON parsing fails, wrap the raw string
                            tc_arguments = {"raw": str(tc.function.arguments)}
                    else:
                        tc_id = tc.get("id", "")
                        tc_function = tc.get("function", {}).get("name", "")
                        tc_args = tc.get("function", {}).get("arguments", "{}")
                        try:
                            tc_arguments = json.loads(tc_args) if isinstance(tc_args, str) else tc_args
                        except (json.JSONDecodeError, TypeError) as e:
                            tc_arguments = {"raw": str(tc_args)}

                    # Handle double-JSON-encoding
                    if isinstance(tc_arguments, str):
                        try:
                            tc_arguments = json.loads(tc_arguments)
                        except (json.JSONDecodeError, TypeError):
                            tc_arguments = {"raw": tc_arguments}

                    tool_calls_inspect.append(
                        ToolCall(
                            id=tc_id,
                            function=tc_function,
                            arguments=tc_arguments,
                            type="function"
                        )
                    )
                except Exception as e:
                    print(f"Warning: Skipping malformed tool call: {e}")
                    continue

            return ChatMessageAssistant(content=content, tool_calls=tool_calls_inspect if tool_calls_inspect else None)

    # For all other cases, use the original function
    return original_convert(message)

InspectEvalAdapter._convert_chat_message_to_inspect = patched_convert


def convert_pkl_to_eval(pkl_path: str, eval_path: str = None, model_name: str = None, task_name: str = None):
    """
    Convert a pickle file to Inspect AI .eval format.

    Args:
        pkl_path: Path to the input .pkl file
        eval_path: Path for the output .eval file (defaults to same name with .eval extension)
        model_name: Model name for the eval log (extracted from pkl if not provided)
        task_name: Task name for the eval log (extracted from filename if not provided)
    """
    pkl_path = Path(pkl_path)

    if eval_path is None:
        eval_path = pkl_path.with_suffix('.eval')
    else:
        eval_path = Path(eval_path)

    if task_name is None:
        task_name = pkl_path.stem  # Use filename without extension

    print(f"Loading {pkl_path}...")

    with open(pkl_path, 'rb') as f:
        data = pickle.load(f)

    # Extract results from the dict
    results = data['results']

    # Try to extract model name from results if not provided
    if model_name is None:
        # Check if there's model info in the results
        model_name = "unknown"  # Default fallback

    print(f"Converting to .eval format at {eval_path}...")

    # Convert using the InspectEvalAdapter
    InspectEvalAdapter.save_as_eval(
        outputs=results,
        model_name=model_name,
        output_path=str(eval_path),
        task_name=task_name,
        compute_summary_stats=True,
        compute_segment_stats=True,
    )

    print(f"Conversion complete! Saved to {eval_path}")


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description="Convert pkl evaluation results to Inspect AI .eval format")
    parser.add_argument("pkl_path", help="Path to input .pkl file")
    parser.add_argument("--eval-path", help="Path for output .eval file (default: same as pkl with .eval extension)")
    parser.add_argument("--model-name", help="Model name for the eval log")
    parser.add_argument("--task-name", help="Task name for the eval log (default: filename)")

    args = parser.parse_args()

    convert_pkl_to_eval(
        pkl_path=args.pkl_path,
        eval_path=args.eval_path,
        model_name=args.model_name,
        task_name=args.task_name,
    )